#include "dk_phrase.inc"
#include "prism.h"

.SECTION/PM seg_pmco;
.GLOBAL _prism_space;

// Four short, unequal feedback lines form a bounded decorrelating network.
// Hadamard cross-coupling is normalized (1/2), and feedback is <=0.999. Capture
// memory is never a feedback destination. HP/LP apply to the processed return.
_prism_space:
    I0 = DM(PS_OUTPUT,I5);
    R0 = I0;
    R1 = 128;
    R2 = R0 + R1;
    I1 = R2;
    R9 = DM(PS_SPACE_INDEX,I5);
    F12 = DM(PC_DIFF,I5);
    R0 = 0;
    F12 = MAX(F12,F0);
    R0 = 0x3f800000;
    F12 = MIN(F12,F0);
    F13 = DM(PC_DECAY,I5);
    R0 = 0;
    F13 = MAX(F13,F0);
    R0 = 0x3f7fbe77; // 0.999
    F13 = MIN(F13,F0);
    F14 = DM(PC_HPF,I5);
    F15 = DM(PC_LPF,I5);
    R0 = 0;
    F14 = MAX(F14,F0);
    F15 = MAX(F15,F0);
    R0 = 0x3f800000;
    F14 = MIN(F14,F0);
    F15 = MIN(F15,F0);
    // All SPACE controls move over the32 samples, keeping edits continuous.
    R0 = 0x3d000000;
    F1 = DM(PS_DIFF_CURRENT,I5);
    F2 = F12 - F1;
    F3 = F2 * F0;
    DM(PS_DIFF_STEP,I5) = R3;
    R12 = R1;
    F1 = DM(PS_DECAY_CURRENT,I5);
    F2 = F13 - F1;
    F3 = F2 * F0;
    DM(PS_DECAY_STEP,I5) = R3;
    R13 = R1;
    F1 = DM(PS_HPF_CURRENT,I5);
    F2 = F14 - F1;
    F3 = F2 * F0;
    DM(PS_HPF_STEP,I5) = R3;
    R14 = R1;
    F1 = DM(PS_LPF_CURRENT,I5);
    F2 = F15 - F1;
    F3 = F2 * F0;
    DM(PS_LPF_STEP,I5) = R3;
    R15 = R1;
    R0 = 32;
    DM(PS_TEMP7,I5) = R0;
_ps_sample:
    F0 = DM(PS_DIFF_STEP,I5);
    F1 = F12 + F0;
    R12 = R1;
    F0 = DM(PS_DECAY_STEP,I5);
    F1 = F13 + F0;
    R13 = R1;
    F0 = DM(PS_HPF_STEP,I5);
    F1 = F14 + F0;
    R14 = R1;
    F0 = DM(PS_LPF_STEP,I5);
    F1 = F15 + F0;
    R15 = R1;
    F10 = DM(I0,M5);
    F11 = DM(I1,M5);
    R0 = I5;
    R1 = PS_SPACE_LINE0 * 4;
    R2 = R0 + R1;
    R0 = 71;
    R1 = R9 - R0;
    R0 = 255;
    R3 = R1 AND R0;
    R0 = LSHIFT R3 BY 2;
    R1 = R2 + R0;
    I2 = R1;
    F4 = DM(0,I2);
    R0 = I5;
    R1 = PS_SPACE_LINE1 * 4;
    R2 = R0 + R1;
    R0 = 113;
    R1 = R9 - R0;
    R0 = 255;
    R3 = R1 AND R0;
    R0 = LSHIFT R3 BY 2;
    R1 = R2 + R0;
    I2 = R1;
    F5 = DM(0,I2);
    R0 = I5;
    R1 = PS_SPACE_LINE2 * 4;
    R2 = R0 + R1;
    R0 = 151;
    R1 = R9 - R0;
    R0 = 255;
    R3 = R1 AND R0;
    R0 = LSHIFT R3 BY 2;
    R1 = R2 + R0;
    I2 = R1;
    F6 = DM(0,I2);
    R0 = I5;
    R1 = PS_SPACE_LINE3 * 4;
    R2 = R0 + R1;
    R0 = 211;
    R1 = R9 - R0;
    R0 = 255;
    R3 = R1 AND R0;
    R0 = LSHIFT R3 BY 2;
    R1 = R2 + R0;
    I2 = R1;
    F7 = DM(0,I2);
    // Feedback Hadamard matrix: energy preserving before decay.
    F0 = F4 + F5;
    F1 = F6 + F7;
    F2 = F0 + F1;
    R3 = 0x3f000000;
    F8 = F2 * F3;
    F2 = F8 * F13;
    R3 = 0x3e800000;
    F0 = F10 * F3;
    F1 = F2 + F0;
    R0 = I5;
    R2 = PS_SPACE_LINE0 * 4;
    R3 = R0 + R2;
    R0 = LSHIFT R9 BY 2;
    R2 = R3 + R0;
    I2 = R2;
    DM(0,I2) = R1;
    F0 = F4 - F5;
    F1 = F6 - F7;
    F2 = F0 + F1;
    R3 = 0x3f000000;
    F8 = F2 * F3;
    F2 = F8 * F13;
    R3 = 0x3e800000;
    F0 = F11 * F3;
    F1 = F2 + F0;
    R0 = I5;
    R2 = PS_SPACE_LINE1 * 4;
    R3 = R0 + R2;
    R0 = LSHIFT R9 BY 2;
    R2 = R3 + R0;
    I2 = R2;
    DM(0,I2) = R1;
    F0 = F4 + F5;
    F1 = F6 + F7;
    F2 = F0 - F1;
    R3 = 0x3f000000;
    F8 = F2 * F3;
    F2 = F8 * F13;
    R3 = 0x3e800000;
    F0 = F10 * F3;
    F1 = F2 - F0;
    R0 = I5;
    R2 = PS_SPACE_LINE2 * 4;
    R3 = R0 + R2;
    R0 = LSHIFT R9 BY 2;
    R2 = R3 + R0;
    I2 = R2;
    DM(0,I2) = R1;
    F0 = F4 - F5;
    F1 = F6 - F7;
    F2 = F0 - F1;
    R3 = 0x3f000000;
    F8 = F2 * F3;
    F2 = F8 * F13;
    R3 = 0x3e800000;
    F0 = F11 * F3;
    F1 = F2 - F0;
    R0 = I5;
    R2 = PS_SPACE_LINE3 * 4;
    R3 = R0 + R2;
    R0 = LSHIFT R9 BY 2;
    R2 = R3 + R0;
    I2 = R2;
    DM(0,I2) = R1;
    // DIFF crossfades the direct grains with the stereo diffused result.
    F0 = F4 + F6;
    F1 = F5 + F7;
    F2 = F0 - F10;
    F3 = F1 - F11;
    F0 = F2 * F12;
    F1 = F3 * F12;
    F2 = F10 + F0;
    F3 = F11 + F1;
    // Low-pass coefficient is one-pole feed-forward amount 0..1.
    F0 = DM(PS_FILTER_LP_L,I5);
    F1 = F2 - F0;
    F4 = F1 * F15;
    F2 = F0 + F4;
    DM(PS_FILTER_LP_L,I5) = R2;
    F0 = DM(PS_FILTER_LP_R,I5);
    F1 = F3 - F0;
    F4 = F1 * F15;
    F3 = F0 + F4;
    DM(PS_FILTER_LP_R,I5) = R3;
    // High-pass is input minus a second low-pass; zero is a true bypass.
    F0 = DM(PS_FILTER_HP_L,I5);
    F1 = F2 - F0;
    F4 = F1 * F14;
    F5 = F0 + F4;
    DM(PS_FILTER_HP_L,I5) = R5;
    F10 = F2 - F5;
    F0 = DM(PS_FILTER_HP_R,I5);
    F1 = F3 - F0;
    F4 = F1 * F14;
    F5 = F0 + F4;
    DM(PS_FILTER_HP_R,I5) = R5;
    F11 = F3 - F5;
    R0 = 0;
    COMP(F14,F0);
    IF NE JUMP _ps_crop_bridge;
    R10 = R2;
    R11 = R3;
_ps_crop_bridge:
    R0 = DM(PS_SMOOTH,I5);
    R0 = PASS R0;
    IF EQ JUMP _ps_store;
    // Exponential sample bridge reaches the new output without retaining an
    // old-bank reader. Exactly64samples then ordinary output resumes.
    R8 = R0;
    F0 = DM(PS_LAST_LEFT,I5);
    F1 = DM(PS_LAST_RIGHT,I5);
    F2 = F10 - F0;
    F3 = F11 - F1;
    F4 = FLOAT R8;
    F5 = RECIPS F4;
    F4 = F2 * F5;
    F6 = F3 * F5;
    F10 = F0 + F4;
    F11 = F1 + F6;
    R0 = R8 - 1;
    DM(PS_SMOOTH,I5) = R0;
_ps_store:
    R0 = 0x40fccccd; // 7.9; leave the framework's8.0guard margin
    R1 = 0xc0fccccd;
    F2 = MIN(F10,F0);
    F3 = MAX(F2,F1);
    DM(I0,M6) = R3;
    DM(PS_LAST_LEFT,I5) = R3;
    F2 = MIN(F11,F0);
    F3 = MAX(F2,F1);
    DM(I1,M6) = R3;
    DM(PS_LAST_RIGHT,I5) = R3;
    R0 = R9 + 1;
    R1 = 255;
    R9 = R0 AND R1;
    R0 = DM(PS_TEMP7,I5);
    R0 = R0 - 1;
    DM(PS_TEMP7,I5) = R0;
    IF GT JUMP _ps_sample;
    DM(PS_SPACE_INDEX,I5) = R9;
    DM(PS_DIFF_CURRENT,I5) = R12;
    DM(PS_DECAY_CURRENT,I5) = R13;
    DM(PS_HPF_CURRENT,I5) = R14;
    DM(PS_LPF_CURRENT,I5) = R15;
    RTS;
