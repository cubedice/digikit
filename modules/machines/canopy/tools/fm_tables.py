"""Reproducible CANOPY FM sine and 31-tap halfband decimator data.

Run ``uv run python -m modules.machines.canopy.tools.fm_tables`` to regenerate.
The halfband has exact zero odd taps except its 0.5 center; normalize the
nonzero side taps to unity DC without destroying the polyphase structure.
"""

from __future__ import annotations

import math
import struct
from pathlib import Path

RATIOS = (
    0.25,
    0.5,
    0.75,
    1,
    1.25,
    math.sqrt(2),
    1.5,
    math.sqrt(3),
    2,
    2.5,
    3,
    4,
    5,
    6,
    7,
    8,
)


def halfband() -> list[float]:
    taps = []
    for n in range(31):
        k = n - 15
        window = (
            0.42
            - 0.5 * math.cos(2 * math.pi * n / 30)
            + 0.08 * math.cos(4 * math.pi * n / 30)
        )
        taps.append(
            0.5
            if k == 0
            else math.sin(math.pi * k / 2) / (math.pi * k) * window
            if n % 2 == 0
            else 0.0
        )
    scale = 0.5 / sum(taps[::2])
    return [value * scale if n % 2 == 0 else value for n, value in enumerate(taps)]


def assembly() -> str:
    lines = [
        "// Generated by modules.machines.canopy.tools.fm_tables; original analytic data.",
        ".SECTION/DM seg_dmda;",
    ]
    for name, values in (
        ("sines", [math.sin(2 * math.pi * n / 1024) for n in range(1024)] + [0.0]),
        ("ratios", RATIOS),
        ("halfband", halfband()[0:15:2]),
    ):
        lines.append(f".GLOBAL _fm_{name};")
        for n, value in enumerate(values):
            bits = struct.unpack("<I", struct.pack("<f", value))[0]
            label = f"_fm_{name}" + (f"_{n}" if n else "")
            lines.append(f".VAR {label} = 0x{bits:08x};")
    return "\n".join(lines) + "\n"


def main() -> None:
    module = Path(__file__).resolve().parents[1]
    (module / "src/dsp/fm-tables.s").write_text(assembly())


if __name__ == "__main__":
    main()
