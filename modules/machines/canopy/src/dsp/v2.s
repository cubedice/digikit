// Stage-1 V2 callbacks. Instance: bank[256], pedals[256], generation, track,
// revision, initialized. The adapter supplies validated normalized event buffers.
// Fixed sine PLAY controls: one word equal to 1; tuning is neutral in this proof.
.SECTION/PM seg_pmco;
.GLOBAL _canopy_reset;
.GLOBAL _canopy_process;
.EXTERN _cp_apply_packed;
.EXTERN _cp_render;
_canopy_reset:
    R0 = PASS R8;
    IF LE JUMP _cv_bad;
    R0 = 4;
    COMP(R8, R0);
    IF GT JUMP _cv_bad;
    R0 = 2;
    COMP(R8, R0);
    IF EQ JUMP _cv_replace;
    I0 = R4;
    R1 = 132;
    R0 = 0;
_cv_reset_clear:
    DM(I0, M6) = R0;
    R1 = R1 - 1;
    IF NE JUMP _cv_reset_clear;
    JUMP (M13, I13);
_cv_replace:
    I0 = R4;
    R1 = 6;
_cv_replace_slots:
    R0 = 2;
    DM(1, I0) = R0;
    MODIFY(I0, 8) (NW);
    R1 = R1 - 1;
    IF NE JUMP _cv_replace_slots;
    // Discard pending onsets, pedal ownership and generation metadata. The six
    // oscillator slots retain phase/gain through their at-most-64-sample ramp.
    R1 = 84;
    R0 = 0;
_cv_replace_clear:
    DM(I0, M6) = R0;
    R1 = R1 - 1;
    IF NE JUMP _cv_replace_clear;
    JUMP (M13, I13);
_canopy_process:
    DM(_cv_state) = R4;
    DM(_cv_input) = R8;
    I2 = R8;
    R0 = DM(0, I2);
    R1 = 2;
    COMP(R0, R1);
    IF NE JUMP _cv_bad;
    R0 = DM(1, I2);
    R1 = 72;
    COMP(R0, R1);
    IF NE JUMP _cv_bad;
    R0 = DM(2, I2);
    R1 = 15;
    R1 = R0 AND R1;
    COMP(R0, R1);
    IF NE JUMP _cv_bad;
    R0 = DM(3, I2);
    R0 = PASS R0;
    IF EQ JUMP _cv_bad;
    R0 = DM(6, I2);
    R0 = PASS R0;
    IF NE JUMP _cv_bad;
    R0 = DM(10, I2);
    R1 = 1;
    COMP(R0, R1);
    IF NE JUMP _cv_bad;
    R0 = DM(9, I2);
    I0 = R0;
    R0 = DM(0, I0);
    COMP(R0, R1);
    IF NE JUMP _cv_bad;
    R0 = DM(11, I2);
    R0 = PASS R0;
    IF EQ JUMP _cv_bad;
    R0 = DM(_cv_state);
    R1 = 512;
    R0 = R0 + R1;
    I0 = R0;
    R0 = DM(3, I0);
    R0 = PASS R0;
    IF EQ JUMP _cv_events;
    R0 = DM(0, I0);
    R1 = DM(3, I2);
    COMP(R0, R1);
    IF NE JUMP _cv_bad;
    R0 = DM(1, I0);
    R1 = DM(2, I2);
    COMP(R0, R1);
    IF NE JUMP _cv_bad;
_cv_events:
    R2 = DM(8, I2);
    R0 = 7;
    R1 = R2 - 1;
    R0 = R0 AND R1;
    COMP(R0, R1);
    IF EQ JUMP _cv_convert;
    R2 = PASS R2;
    IF EQ JUMP _cv_render;
    JUMP _cv_bad;
_cv_convert:
    R0 = DM(7, I2);
    I0 = R0;
    I1 = _cv_events_buffer;
_cv_event:
    R3 = DM(0, I0);
    R5 = DM(1, I0);
    R6 = DM(2, I0);
    R7 = DM(3, I0);
    R9 = DM(4, I0);
    R0 = DM(5, I0);
    R0 = PASS R0;
    IF NE JUMP _cv_bad;
    R0 = 0xfffffef0;
    R0 = R5 AND R0;
    IF NE JUMP _cv_bad;
    R0 = 15;
    R10 = R5 AND R0;
    R10 = LSHIFT R10 BY 6;
    R5 = LSHIFT R5 BY -8;
    R5 = LSHIFT R5 BY 4;
    R10 = R10 OR R5;
    R0 = 1;
    COMP(R3, R0);
    IF EQ JUMP _cv_note;
    R0 = 2;
    COMP(R3, R0);
    IF EQ JUMP _cv_note;
    R6 = PASS R6;
    IF NE JUMP _cv_bad;
    R0 = 3;
    COMP(R3, R0);
    IF EQ JUMP _cv_cc;
    R0 = 4;
    COMP(R3, R0);
    IF NE JUMP _cv_bad;
    R7 = PASS R7;
    IF NE JUMP _cv_bad;
    R0 = 0xffffc000;
    R0 = R9 AND R0;
    IF NE JUMP _cv_bad;
    R0 = 127;
    R7 = R9 AND R0;
    R9 = LSHIFT R9 BY -7;
    JUMP _cv_pack;
_cv_note:
    R6 = PASS R6;
    IF EQ JUMP _cv_bad;
    R0 = 0xffff80ff;
    R1 = R7 OR R9;
    R0 = R1 AND R0;
    IF NE JUMP _cv_bad;
    R7 = LSHIFT R7 BY -8;
    R9 = LSHIFT R9 BY -8;
    R0 = 1;
    COMP(R3, R0);
    IF NE JUMP _cv_pack;
    R9 = PASS R9;
    IF EQ JUMP _cv_bad;
    JUMP _cv_pack;
_cv_cc:
    R0 = 0xffffff80;
    R1 = R7 OR R9;
    R0 = R1 AND R0;
    IF NE JUMP _cv_bad;
_cv_pack:
    R7 = LSHIFT R7 BY 14;
    R9 = LSHIFT R9 BY 21;
    R0 = R10 OR R3;
    R0 = R0 OR R7;
    R0 = R0 OR R9;
    DM(I1, M6) = R6;
    R1 = 0;
    DM(I1, M6) = R1;
    DM(I1, M6) = R0;
    MODIFY(I0, 6) (NW);
    R2 = R2 - 1;
    IF NE JUMP _cv_event;
    R4 = DM(_cv_state);
    R0 = 256;
    R8 = R4 + R0;
    R12 = _cv_events_buffer;
    R0 = DM(_cv_input);
    I0 = R0;
    R9 = DM(8, I0);
    CALL _cp_apply_packed;
    R1 = 1;
    COMP(R0, R1);
    IF NE JUMP _cv_bad;
_cv_render:
    R0 = DM(_cv_state);
    R1 = 512;
    R0 = R0 + R1;
    I0 = R0;
    R0 = DM(_cv_input);
    I2 = R0;
    R0 = DM(3, I2);
    DM(0, I0) = R0;
    R0 = DM(2, I2);
    DM(1, I0) = R0;
    R0 = DM(11, I2);
    DM(2, I0) = R0;
    R0 = 1;
    DM(3, I0) = R0;
    R8 = DM(5, I2);
    R4 = DM(_cv_state);
    CALL _cp_render;
    R1 = 1;
    R0 = R1 - R0;
    JUMP (M13, I13);
_cv_bad:
    R0 = -1;
    JUMP (M13, I13);
