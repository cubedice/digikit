// Atomic CPSA upper-bank validation. Return low-word validation copy in I0.
_fm_validate:
    I0 = R4;
    I1 = _fm_low;
    R2 = 16;
_fm_header:
    R0 = DM(I0,M6);
    DM(I1,M6) = R0;
    R2 = R2 - 1;
    IF NE JUMP _fm_header;
    I2 = R4;
    R5 = DM(0,I2);
    R5 = FEXT R5 BY 0:8;
    I2 = _fm_limits;
    R2 = 16;
_fm_validate_loop:
    R0 = DM(I0,M6);
    R1 = LSHIFT R0 BY -16;
    R3 = DM(I2,M6);
    R6 = 4;
    COMP(R2,R6);
    IF GT JUMP _fm_validate_limit;
    R6 = 11;
    COMP(R5,R6);
    R6 = 0;
    IF NE R3 = R6;
_fm_validate_limit:
    COMP(R1,R3);
    IF GT JUMP _fm_invalid;
    R0 = FEXT R0 BY 0:16;
    DM(I1,M6) = R0;
    R2 = R2 - 1;
    IF NE JUMP _fm_validate_loop;
    I0 = _fm_low;
    R0 = 1;
    RTS;
_fm_invalid:
    R0 = 0;
    RTS;

