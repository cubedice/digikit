// CANOPY bounded harmonic pad kernel. Internal ABI, not a loadable V1 machine.
// Bank: four foreground + two tail slots, each 32 bytes:
// {token, gate, x, y, sin(w), cos(w), gain, envelope}; then four 16-byte
// pending replacements {token,note,velocity,signed_bend}. 256 bytes per track.
// R4=bank for all calls; note_on: R8=nonzero token,R12=MIDI note,R9=velocity.
// note_off: R8=token. render: R8=32-float output. Returns R0=1 accepted/active,
// 0 rejected/quiet. Scratch R0..15,I0..2; L0..2=0,M5=0,M6=1, non-SIMD floats.
// Gate 2 is the reset/steal ramp (at most 64 samples). Reclaim the quietest
// release first, otherwise the oldest token (CF tokens increase per epoch).
// A silent new onset needs no
// tail. Both tails busy => queue a replacement behind its own 64-sample ramp.
.SECTION/PM seg_pmco;
.GLOBAL _cp_note_on;
.GLOBAL _cp_note_off;
.GLOBAL _cp_render;
.EXTERN _cp_tuning;
_cp_note_on:
    R8 = PASS R8;
    IF EQ JUMP _cp_reject;
    R0 = LSHIFT R12 BY -7;
    R0 = PASS R0;
    IF NE JUMP _cp_reject;
    R0 = LSHIFT R9 BY -7;
    R0 = PASS R0;
    IF NE JUMP _cp_reject;
    R9 = PASS R9;
    IF EQ JUMP _cp_reject;
    I0 = R4;
    R2 = 6;
_cp_unique_token:
    R0 = DM(0, I0);
    COMP(R0, R8);
    IF EQ JUMP _cp_reject;
    MODIFY(I0, 8) (NW);
    R2 = R2 - 1;
    IF NE JUMP _cp_unique_token;
    R2 = 4;
_cp_unique_pending:
    R0 = DM(0, I0);
    COMP(R0, R8);
    IF EQ JUMP _cp_reject;
    MODIFY(I0, 4) (NW);
    R2 = R2 - 1;
    IF NE JUMP _cp_unique_pending;
    I0 = R4;
    R0 = 192;
    R0 = R4 + R0;
    I1 = R0;
    R2 = 4;
    R3 = 0;
    R6 = 0;
    R5 = 0;
_cp_find_slot:
    R0 = DM(0, I0);
    R1 = DM(0, I1);
    R1 = PASS R1;
    IF NE R0 = R1; // pending replacement is the current foreground owner
    R0 = PASS R0;
    IF NE JUMP _cp_oldest;
    R3 = I0;
    JUMP _cp_next_slot;
_cp_oldest:
    R1 = 0x80000000;
    R10 = R0 XOR R1;
    R15 = 0;
    R1 = DM(0, I1);
    R1 = PASS R1;
    IF NE JUMP _cp_compare_candidate; // queued onset remains a held owner
    R0 = DM(1, I0);
    R1 = 1;
    COMP(R0, R1);
    IF NE R15 = R1;
_cp_compare_candidate:
    R14 = DM(7, I0); // nonnegative float bits sort by envelope magnitude
    R6 = PASS R6;
    IF EQ JUMP _cp_choose_oldest;
    COMP(R15, R5);
    IF GT JUMP _cp_choose_oldest; // releasing before held
    IF LT JUMP _cp_next_slot;
    R15 = PASS R15;
    IF EQ JUMP _cp_compare_age;
    COMP(R14, R13);
    IF LT JUMP _cp_choose_oldest;
    IF GT JUMP _cp_next_slot;
_cp_compare_age:
    COMP(R10, R7);
    IF GE JUMP _cp_next_slot;
_cp_choose_oldest:
    R6 = I0;
    R7 = R10;
    R5 = R15;
    R13 = R14;
_cp_next_slot:
    MODIFY(I0, 8) (NW);
    MODIFY(I1, 4) (NW);
    R2 = R2 - 1;
    IF NE JUMP _cp_find_slot;
    R3 = PASS R3;
    IF NE JUMP _cp_start;
    R3 = R6;
    R0 = R3 - R4;
    R0 = LSHIFT R0 BY -1;
    R1 = 192;
    R0 = R0 + R1;
    R0 = R4 + R0;
    I2 = R0;
    R0 = DM(0, I2);
    R0 = PASS R0;
    IF NE JUMP _cp_queue_replacement;
    I0 = R3;
    R0 = DM(7, I0);
    R0 = PASS R0;
    IF EQ JUMP _cp_start; // an unrendered onset is silent; no tail required
    R0 = 128;
    R0 = R4 + R0;
    I2 = R0;
    R2 = 2;
_cp_find_tail:
    R0 = DM(0, I2);
    R0 = PASS R0;
    IF EQ JUMP _cp_save_tail;
    MODIFY(I2, 8) (NW);
    R2 = R2 - 1;
    IF NE JUMP _cp_find_tail;
    R0 = R3 - R4;
    R0 = LSHIFT R0 BY -1;
    R1 = 192;
    R0 = R0 + R1;
    R0 = R4 + R0;
    I2 = R0;
_cp_queue_replacement:
    DM(0, I2) = R8;
    DM(1, I2) = R12;
    DM(2, I2) = R9;
    R0 = 0;
    DM(3, I2) = R0;
    I0 = R3;
    R0 = 2;
    DM(1, I0) = R0;
    R0 = 1;
    RTS;
_cp_save_tail:
    R11 = I2;
    I1 = R3;
    R2 = 8;
_cp_copy_tail:
    R0 = DM(I1, M6);
    DM(I2, M6) = R0;
    R2 = R2 - 1;
    IF NE JUMP _cp_copy_tail;
    I2 = R11;
    R0 = 2;
    DM(1, I2) = R0;
_cp_start:
    I0 = R3;
    DM(0, I0) = R8;
    R0 = 1;
    DM(1, I0) = R0;
    R0 = 0;
    DM(2, I0) = R0;
    DM(7, I0) = R0;
    F0 = 1.0;
    DM(3, I0) = R0;
    R0 = LSHIFT R12 BY 3;
    R1 = _cp_tuning;
    R0 = R0 + R1;
    I1 = R0;
    R0 = DM(0, I1);
    DM(4, I0) = R0;
    R0 = DM(1, I1);
    DM(5, I0) = R0;
    F0 = FLOAT R9;
    F1 = 0.007874015748;
    F0 = F0 * F1;
    DM(6, I0) = R0;
    R0 = 1;
    RTS;
_cp_note_off:
    R8 = PASS R8;
    IF EQ JUMP _cp_reject;
    R0 = 192;
    R0 = R4 + R0;
    I0 = R0;
    R2 = 4;
_cp_release_pending:
    R0 = DM(0, I0);
    COMP(R0, R8);
    IF EQ JUMP _cp_cancel_pending;
    MODIFY(I0, 4) (NW);
    R2 = R2 - 1;
    IF NE JUMP _cp_release_pending;
    I0 = R4;
    R2 = 6;
_cp_find_release:
    R0 = DM(0, I0);
    COMP(R0, R8);
    IF EQ JUMP _cp_release;
    MODIFY(I0, 8) (NW);
    R2 = R2 - 1;
    IF NE JUMP _cp_find_release;
    JUMP _cp_reject;
_cp_cancel_pending:
    R0 = 0;
    DM(0, I0) = R0;
    R0 = 1;
    RTS;
_cp_release:
    R0 = DM(1, I0);
    R1 = 2;
    COMP(R0, R1);
    IF EQ JUMP _cp_release_done; // do not lengthen a reset ramp
    R0 = 0;
    DM(1, I0) = R0;
_cp_release_done:
    R0 = 1;
    RTS;
_cp_reject:
    R0 = 0;
    RTS;
_cp_render:
    I2 = R8;
    R0 = 0;
    R1 = 32;
_cp_clear_output:
    DM(I2, M6) = R0;
    R1 = R1 - 1;
    IF NE JUMP _cp_clear_output;
    I0 = R4;
    R11 = R4;
    R14 = 6;
    R15 = 0;
_cp_render_slot:
    R0 = DM(0, I0);
    R0 = PASS R0;
    IF EQ JUMP _cp_render_next;
    // Keep the shared carrier held for the whole block containing a tail's
    // final samples. QUIET is safe only on the following empty block.
    R15 = 1;
    F2 = DM(2, I0); // oscillator x,y
    F3 = DM(3, I0);
    F4 = DM(4, I0); // rotation sin,cos
    F5 = DM(5, I0);
    F6 = DM(6, I0);
    F7 = DM(7, I0);
    R0 = DM(1, I0);
    F10 = DM(_cp_attack); // per-note linear attack
    R1 = 2;
    COMP(R0, R1);
    IF EQ JUMP _cp_reset_ramp;
    R0 = PASS R0;
    IF NE JUMP _cp_render_samples;
    F10 = DM(_cp_release_step);
    JUMP _cp_render_samples;
_cp_reset_ramp:
    F10 = -0.015625; // bounded de-click ramp on lifecycle reset
_cp_render_samples:
    // Drift is a bounded small rotation of the base pitch coefficients. Never
    // accumulate it into tuning; MIDI bend continues to own the base rotation.
    R1 = DM(0, I0);
    R9 = 1;
    R1 = R1 AND R9;
    F0 = DM(_cp_drift);
    IF EQ F0 = -F0;
    F0 = F0 * F4;
    F1 = F0 * F0;
    F9 = 0.5;
    F1 = F1 * F9;
    F9 = 1.0;
    F1 = F9 - F1;
    F9 = F4 * F1;
    F12 = F5 * F0;
    F9 = F9 + F12;
    F5 = F5 * F1;
    F0 = F4 * F0;
    F5 = F5 - F0;
    F4 = F9;
    // Harmonics fade out BEFORE Nyquist, using the bent/drifted coefficient.
    F0 = 0.05;
    F12 = F5 - F0;
    F0 = 4.0;
    F12 = F12 * F0;
    F1 = 0.0;
    F12 = MAX(F12, F1);
    F1 = 1.0;
    F12 = MIN(F12, F1);
    F0 = DM(_cp_second_step);
    F0 = F12 * F0;
    DM(_cp_h2step) = F0;
    F0 = DM(_cp_second_start);
    F12 = F12 * F0;
    F0 = 0.5;
    F9 = F5 - F0;
    F0 = 4.0;
    F9 = F9 * F0;
    F0 = 0.0;
    F9 = MAX(F9, F0);
    F0 = 1.0;
    F9 = MIN(F9, F0);
    F0 = DM(_cp_third_step);
    F0 = F9 * F0;
    DM(_cp_h3step) = F0;
    F0 = DM(_cp_third_start);
    F9 = F9 * F0;
    DM(_cp_h3) = F9;
    I2 = R8;
    R13 = 32;
_cp_sample:
    F0 = DM(_cp_h2step);
    F12 = F12 + F0;
    F0 = DM(_cp_h3);
    F1 = DM(_cp_h3step);
    F0 = F0 + F1;
    DM(_cp_h3) = F0;
    F7 = F7 + F10;
    F0 = 0.0;
    F7 = MAX(F7, F0);
    F0 = 1.0;
    F7 = MIN(F7, F0);
    F0 = F2 * F5;
    F1 = F3 * F4;
    F9 = F0 + F1;
    F0 = F3 * F5;
    F1 = F2 * F4;
    F3 = F0 - F1;
    F2 = F9;
    // sin(2p)=2xy; sin(3p)=x(3-4x*x). Finite additive spectra,
    // not a clipped/waveshaped oscillator with unbounded high harmonics.
    F0 = F2 * F3;
    F1 = 2.0;
    F0 = F0 * F1;
    F0 = F0 * F12;
    F9 = F2 + F0;
    F0 = F2 * F2;
    F1 = 4.0;
    F0 = F0 * F1;
    F1 = 3.0;
    F0 = F1 - F0;
    F0 = F0 * F2;
    F1 = DM(_cp_h3);
    F0 = F0 * F1;
    F0 = F9 + F0;
    F0 = F0 * F6;
    F0 = F0 * F7;
    F1 = DM(_cp_level);
    F0 = F0 * F1;
    F1 = DM(I2, M5);
    F0 = F0 + F1;
    DM(I2, M6) = F0;
    R13 = R13 - 1;
    IF NE JUMP _cp_sample;
    // One Newton normalization step per block bounds float32 rotation drift.
    F0 = F2 * F2;
    F1 = F3 * F3;
    F0 = F0 + F1;
    F1 = 0.5;
    F0 = F0 * F1;
    F1 = 1.5;
    F0 = F1 - F0;
    F2 = F2 * F0;
    F3 = F3 * F0;
    DM(2, I0) = F2;
    DM(3, I0) = F3;
    DM(7, I0) = F7;
    F0 = 0.0;
    COMP(F7, F0);
    IF GT JUMP _cp_active;
    R0 = 0;
    DM(0, I0) = R0;
    JUMP _cp_render_next;
_cp_active:
    R15 = 1;
_cp_render_next:
    R0 = 2;
    COMP(R14, R0);
    IF LE JUMP _cp_advance_slot;
    R0 = DM(0, I0);
    R0 = PASS R0;
    IF NE JUMP _cp_advance_slot;
    R3 = I0;
    R0 = R3 - R11;
    R0 = LSHIFT R0 BY -1;
    R1 = 192;
    R0 = R0 + R1;
    R0 = R11 + R0;
    I1 = R0;
    R0 = DM(0, I1);
    R0 = PASS R0;
    IF EQ JUMP _cp_advance_slot;
    R13 = R8;
    R8 = R0;
    R12 = DM(1, I1);
    R9 = DM(2, I1);
    R0 = DM(3, I1);
    DM(_cp_pending_bend) = R0;
    R0 = 0;
    DM(0, I1) = R0;
    CALL _cp_start;
    R9 = DM(_cp_pending_bend);
    R9 = PASS R9;
    IF NE CALL _cp_retune;
    R8 = R13;
    R15 = 1;
_cp_advance_slot:
    MODIFY(I0, 8) (NW);
    R14 = R14 - 1;
    IF NE JUMP _cp_render_slot;
    R0 = R15;
    RTS;

// I0=voice slot, R12=base MIDI note, R9=signed bend [-8192,8191].
// +/-2 semitones. Preserve phase/envelope/gain and R8,R11..15,I0.
// Scratch R0..7,R9..10,I1, flags. Rotation by a small delta avoids large-angle
// approximations. exp fifth-order; sin fifth-order; cos sixth-order.
.GLOBAL _cp_retune;
.EXTERN _cp_angles;
_cp_retune:
    R0 = LSHIFT R12 BY 3;
    R1 = _cp_tuning;
    R0 = R0 + R1;
    I1 = R0;
    F6 = DM(0, I1);
    F7 = DM(1, I1);
    R9 = PASS R9;
    IF EQ JUMP _cp_retune_store;
    F0 = FLOAT R9;
    F1 = 0.00001410211549; // ln(2)/(6*8192)
    F0 = F0 * F1;
    F1 = 0.008333333333;
    F1 = F1 * F0;
    F2 = 0.04166666667;
    F1 = F1 + F2;
    F1 = F1 * F0;
    F2 = 0.1666666667;
    F1 = F1 + F2;
    F1 = F1 * F0;
    F2 = 0.5;
    F1 = F1 + F2;
    F1 = F1 * F0;
    F2 = 1.0;
    F1 = F1 + F2;
    F1 = F1 * F0; // exp(x)-1 directly, avoiding cancellation near center
    R0 = LSHIFT R12 BY 2;
    R2 = _cp_angles;
    R0 = R0 + R2;
    I1 = R0;
    F0 = DM(0, I1);
    F0 = F0 * F1; // delta radians/sample
    F1 = F0 * F0;
    F2 = 0.008333333333;
    F2 = F2 * F1;
    F3 = -0.1666666667;
    F2 = F2 + F3;
    F2 = F2 * F1;
    F3 = 1.0;
    F2 = F2 + F3;
    F2 = F2 * F0; // sin(delta)
    F3 = -0.001388888889;
    F3 = F3 * F1;
    F4 = 0.04166666667;
    F3 = F3 + F4;
    F3 = F3 * F1;
    F4 = -0.5;
    F3 = F3 + F4;
    F3 = F3 * F1;
    F4 = 1.0;
    F3 = F3 + F4; // cos(delta)
    F0 = F6 * F3;
    F1 = F7 * F2;
    F4 = F0 + F1;
    F0 = F7 * F3;
    F1 = F6 * F2;
    F7 = F0 - F1;
    F6 = F4;
_cp_retune_store:
    DM(4, I0) = R6;
    DM(5, I0) = R7;
    RTS;
