// R8 points to two channel pointers for this callback. Make an owned block
// before the firmware can reuse either source. No modification to dry routing.
.SECTION/PM seg_pmco;
.GLOBAL _relay_input_tap;
.EXTERN _relay_input_tail;
.EXTERN _rtm_capture;
.EXTERN _tk_pool_fold;
_relay_input_tap:
    DM(_ri_r0) = R0;
    R0 = MODE1;
    DM(_ri_mode) = R0;
    BIT CLR MODE1 0x200000;
    NOP;
    NOP;
    R0 = I0;
    DM(_ri_i0) = R0;
    R0 = I1;
    DM(_ri_i1) = R0;
    R0 = M6;
    DM(_ri_m6) = R0;
    R0 = L0;
    DM(_ri_l0) = R0;
    R0 = L1;
    DM(_ri_l1) = R0;
    L0 = 0;
    L1 = 0;
    M6 = 1;
    I0 = R8;
    R0 = DM(0,I0);
    I0 = R0;
    I1 = _relay_external;
    LCNTR = 32, DO _ri_left UNTIL LCE;
        R0 = DM(I0,M6);
_ri_left: DM(I1,M6) = R0;
    I0 = R8;
    R0 = DM(1,I0);
    I0 = R0;
    LCNTR = 32, DO _ri_right UNTIL LCE;
        R0 = DM(I0,M6);
_ri_right: DM(I1,M6) = R0;
    R0 = ASTATX;
    DM(_ri_astat) = R0;
    R0 = _tk_pool_fold;
    R0 = PASS R0;
    IF NE CALL _tk_pool_fold;
    R0 = _rtm_capture;
    R0 = PASS R0;
    IF NE CALL _rtm_capture;
    R0 = DM(_ri_astat);
    ASTATX = R0;
    R0 = DM(_ri_i0);
    I0 = R0;
    R0 = DM(_ri_i1);
    I1 = R0;
    R0 = DM(_ri_l0);
    L0 = R0;
    R0 = DM(_ri_l1);
    L1 = R0;
    R0 = DM(_ri_m6);
    M6 = R0;
    R0 = DM(_ri_mode);
    MODE1 = R0;
    NOP;
    NOP;
    R0 = DM(_ri_r0);
    JUMP _relay_input_tail;

// The block handler's scalar CALL to the Q31 converter is retargeted here.
// No DO is active. Copy the finalized planar stereo float block, then enter
// the original converter with its arguments, arithmetic flags and PC stack.
.GLOBAL _relay_main_tap;
.EXTERN _relay_q31_converter;
.EXTERN _relay_master_float;
_relay_main_tap:
    DM(_rm_r0) = R0;
    R0 = MODE1;
    DM(_rm_mode) = R0;
    BIT CLR MODE1 0x200000;
    NOP;
    NOP;
    R0 = I0;
    DM(_rm_i0) = R0;
    R0 = I1;
    DM(_rm_i1) = R0;
    R0 = L0;
    DM(_rm_l0) = R0;
    R0 = L1;
    DM(_rm_l1) = R0;
    R0 = M6;
    DM(_rm_m6) = R0;
    R0 = LCNTR;
    DM(_rm_lcntr) = R0;
    L0 = 0;
    L1 = 0;
    M6 = 1;
    I0 = _relay_master_float;
    I1 = _relay_main;
    LCNTR = 64, DO _rm_sample UNTIL LCE;
        R0 = DM(I0,M6);
_rm_sample: DM(I1,M6) = R0;
    R0 = DM(_rm_i0);
    I0 = R0;
    R0 = DM(_rm_i1);
    I1 = R0;
    R0 = DM(_rm_l0);
    L0 = R0;
    R0 = DM(_rm_l1);
    L1 = R0;
    R0 = DM(_rm_m6);
    M6 = R0;
    R0 = DM(_rm_lcntr);
    LCNTR = R0;
    R0 = DM(_rm_mode);
    MODE1 = R0;
    NOP;
    NOP;
    R0 = DM(_rm_r0);
    JUMP _relay_q31_converter;

.SECTION/DM seg_dmda;
.GLOBAL _relay_external;
.VAR _relay_external[64];
// Stores before PEYEN is cleared can write both lanes. Keep each pair
// together so the scalar save of L0 cannot overwrite the saved S0.
.VAR _ri_r0[2];
.VAR _ri_mode[2];
.VAR _ri_astat;
.VAR _ri_i0;
.VAR _ri_i1;
.VAR _ri_l0;
.VAR _ri_l1;
.VAR _ri_m6;

.GLOBAL _relay_main;
.VAR _relay_main[64];
.VAR _rm_r0[2];
.VAR _rm_mode[2];
.VAR _rm_i0;
.VAR _rm_i1;
.VAR _rm_l0;
.VAR _rm_l1;
.VAR _rm_m6;
.VAR _rm_lcntr;
