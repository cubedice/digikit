// Composed early-frame instrument bridge. I3 is the stock receive ring.
// Preserves R/S0..15, I0..2, M5/M6, L0..2, MODE1 and arithmetic status.
// Consumers must preserve all other live registers and return via RTS.
// Runs with linear addressing and non-SIMD wrapping integer arithmetic.
.SECTION/PM seg_pmco;
.GLOBAL _instrument_block;
.EXTERN _mi_receive;
.EXTERN _mi_reply_build;
.EXTERN _mi_carrier_begin;
_instrument_block:
    DM(_mi_block_save + 0) = R0;
    DM(_mi_block_save + 8) = R1;
    DM(_mi_block_save + 16) = R2;
    DM(_mi_block_save + 24) = R3;
    DM(_mi_block_save + 32) = R4;
    DM(_mi_block_save + 40) = R5;
    DM(_mi_block_save + 48) = R6;
    DM(_mi_block_save + 56) = R7;
    DM(_mi_block_save + 64) = R8;
    DM(_mi_block_save + 72) = R9;
    DM(_mi_block_save + 80) = R10;
    DM(_mi_block_save + 88) = R11;
    DM(_mi_block_save + 96) = R12;
    DM(_mi_block_save + 104) = R13;
    DM(_mi_block_save + 112) = R14;
    DM(_mi_block_save + 120) = R15;
    R0 = I0;
    DM(_mi_block_save + 128) = R0;
    R0 = I1;
    DM(_mi_block_save + 136) = R0;
    R0 = I2;
    DM(_mi_block_save + 144) = R0;
    R0 = M5;
    DM(_mi_block_save + 152) = R0;
    R0 = M6;
    DM(_mi_block_save + 160) = R0;
    R0 = L0;
    DM(_mi_block_save + 168) = R0;
    R0 = L1;
    DM(_mi_block_save + 176) = R0;
    R0 = L2;
    DM(_mi_block_save + 184) = R0;
    R0 = MODE1;
    DM(_mi_block_save + 192) = R0;
    R0 = ASTATX;
    DM(_mi_block_save + 200) = R0;
    R0 = ASTATY;
    DM(_mi_block_save + 208) = R0;
    R0 = STKYX;
    DM(_mi_block_save + 216) = R0;
    R0 = STKYY;
    DM(_mi_block_save + 224) = R0;
    BIT CLR MODE1 0x202000;
    L0 = 0;
    L1 = 0;
    L2 = 0;
    M5 = 0;
    M6 = 1;
    R0 = _mi_carrier_begin;
    R0 = PASS R0;
    IF EQ JUMP _mi_block_receive;
    CALL _mi_carrier_begin;
_mi_block_receive:
    R0 = I3;
    R1 = 0x9fc;
    R4 = R0 + R1;
    CALL _mi_receive;
    CALL _mi_reply_build;
    R0 = DM(_mi_block_save + 128);
    I0 = R0;
    R0 = DM(_mi_block_save + 136);
    I1 = R0;
    R0 = DM(_mi_block_save + 144);
    I2 = R0;
    R0 = DM(_mi_block_save + 152);
    M5 = R0;
    R0 = DM(_mi_block_save + 160);
    M6 = R0;
    R0 = DM(_mi_block_save + 168);
    L0 = R0;
    R0 = DM(_mi_block_save + 176);
    L1 = R0;
    R0 = DM(_mi_block_save + 184);
    L2 = R0;
    R0 = DM(_mi_block_save + 192);
    MODE1 = R0;
    R0 = DM(_mi_block_save + 200);
    ASTATX = R0;
    R0 = DM(_mi_block_save + 208);
    ASTATY = R0;
    R0 = DM(_mi_block_save + 216);
    STKYX = R0;
    R0 = DM(_mi_block_save + 224);
    STKYY = R0;
    R1 = DM(_mi_block_save + 8);
    R2 = DM(_mi_block_save + 16);
    R3 = DM(_mi_block_save + 24);
    R4 = DM(_mi_block_save + 32);
    R5 = DM(_mi_block_save + 40);
    R6 = DM(_mi_block_save + 48);
    R7 = DM(_mi_block_save + 56);
    R8 = DM(_mi_block_save + 64);
    R9 = DM(_mi_block_save + 72);
    R10 = DM(_mi_block_save + 80);
    R11 = DM(_mi_block_save + 88);
    R12 = DM(_mi_block_save + 96);
    R13 = DM(_mi_block_save + 104);
    R14 = DM(_mi_block_save + 112);
    R15 = DM(_mi_block_save + 120);
    R0 = DM(_mi_block_save);
    RTS;
.PKDATA _mi_block_save, 232;
