    R9 = LSHIFT R8 BY -10;
    R8 = FEXT R8 BY 0:10;
    R0 = 52;
    COMP(R9, R0);
    IF GT JUMP _iv_lock_overlay_advance;
    I0 = _iv_lock_controls;
    R12 = DM(1, I0); // active source family
    R0 = 40;
    COMP(R9, R0);
    IF GE JUMP _iv_lock_overlay_fm;
    R0 = 16;
    COMP(R9, R0);
    IF LT JUMP _iv_lock_overlay_legacy;
    R0 = 31;
    COMP(R9, R0);
