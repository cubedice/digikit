// Exact per-note lock sideband. The ordinary packet is already validated by
// core/midi-events. A locked packet is rejected unless its adjacent sideband
// matches epoch, message, generation, track, padding and checksum. Staging is
// private; the target slot changes only after normal event normalization.
.SECTION/PM seg_pmco;
.GLOBAL _iv_lock_stage;
.GLOBAL _iv_lock_commit;
.GLOBAL _iv_lock_clear;
.EXTERN _iv_slot;
_iv_lock_stage:
    R0 = 0;
    DM(_iv_lock_staged) = R0;
    I0 = R4;
    R0 = DM(1, I0);
    R0 = FEXT R0 BY 12:1;
    R0 = PASS R0;
    IF EQ JUMP _iv_lock_ok;
    R0 = 72;
    R0 = R4 - R0;
    I1 = R0;
    R0 = DM(0, I1);
    R1 = 0x434c4b31;
    COMP(R0, R1);
    IF NE JUMP _iv_lock_bad;
    R0 = DM(1, I1);
    R1 = DM(2, I0);
    COMP(R0, R1);
    IF NE JUMP _iv_lock_bad;
    R0 = DM(2, I1);
    R1 = DM(3, I0);
    COMP(R0, R1);
    IF NE JUMP _iv_lock_bad;
    R0 = DM(3, I1);
    R1 = DM(9, I0);
    COMP(R0, R1);
    IF NE JUMP _iv_lock_bad;
    R0 = DM(4, I1);
    R1 = 0xfffef8f0;
    R1 = R0 AND R1;
    R1 = PASS R1;
    IF NE JUMP _iv_lock_bad;
    R1 = FEXT R0 BY 0:4;
    R2 = DM(10, I0);
    R2 = FEXT R2 BY 10:4;
    COMP(R1, R2);
    IF NE JUMP _iv_lock_bad;
    R6 = FEXT R0 BY 8:3;
    R1 = FEXT R0 BY 16:1;
    DM(_iv_lock_source_flag) = R1;
    R1 = 0;
    DM(_iv_lock_wave_seen) = R1;
    R1 = 5;
    COMP(R6, R1);
    IF GT JUMP _iv_lock_bad;
    R0 = DM(7, I1);
    R0 = LSHIFT R0 BY -16;
    R0 = PASS R0;
    IF NE JUMP _iv_lock_bad;
    R0 = DM(16, I1);
    R0 = LSHIFT R0 BY -16;
    R0 = PASS R0;
    IF NE JUMP _iv_lock_bad;
    // Same wrapping checksum as ml_encode, over words 0..16.
    R1 = 0x6c6f636b;
    R2 = 0x74726967;
    R3 = 17;
    I2 = I1;
_iv_lock_check:
    R0 = DM(I2, M6);
    R1 = R1 + R0;
    R2 = R2 + R1;
    R3 = R3 - 1;
    IF NE JUMP _iv_lock_check;
    R1 = R1 XOR R2;
    R0 = DM(17, I1);
    COMP(R0, R1);
    IF NE JUMP _iv_lock_bad;
    DM(_iv_lock_staging) = R6;
    R5 = 0;
_iv_lock_pair:
    R0 = LSHIFT R5 BY -1;
    R1 = 5;
    R0 = R0 + R1;
    R0 = LSHIFT R0 BY 2;
    R1 = I1;
    R0 = R0 + R1;
    I2 = R0;
    R0 = DM(0, I2);
    R1 = FEXT R5 BY 0:1;
    R1 = LSHIFT R1 BY 4;
    R1 = -R1;
    R0 = LSHIFT R0 BY R1;
    R0 = FEXT R0 BY 0:16;
    COMP(R5, R6);
    IF LT JUMP _iv_lock_pair_active;
    R0 = PASS R0;
    IF NE JUMP _iv_lock_bad;
    JUMP _iv_lock_pair_next;
_iv_lock_pair_active:
    R1 = LSHIFT R0 BY -10;
    R2 = 52;
    COMP(R1, R2);
    IF GT JUMP _iv_lock_bad;
    R2 = 34;
    COMP(R1, R2);
    IF NE JUMP _iv_lock_pair_value;
    R1 = DM(_iv_lock_wave_seen);
    R1 = PASS R1;
    IF NE JUMP _iv_lock_bad;
    R1 = 1;
    DM(_iv_lock_wave_seen) = R1;
    R1 = FEXT R0 BY 0:10;
    DM(_iv_lock_wave_value) = R1;
    R2 = 7;
    COMP(R1, R2);
    IF GT JUMP _iv_lock_bad;
_iv_lock_pair_value:
    R1 = FEXT R0 BY 0:10;
    R2 = 1000;
    COMP(R1, R2);
    IF GT JUMP _iv_lock_bad;
    R1 = LSHIFT R5 BY 2;
    R2 = _iv_lock_staging;
    R3 = 4;
    R2 = R2 + R3;
    R1 = R1 + R2;
    I2 = R1;
    DM(0, I2) = R0;
_iv_lock_pair_next:
    R5 = R5 + 1;
    R0 = 5;
    COMP(R5, R0);
    IF LT JUMP _iv_lock_pair;
    R0 = DM(_iv_lock_wave_seen);
    R1 = DM(_iv_lock_source_flag);
    COMP(R0, R1);
    IF NE JUMP _iv_lock_bad;
    I2 = _iv_lock_staging;
    DM(6, I2) = R1;
    R5 = 0;
_iv_lock_source_copy:
    R0 = LSHIFT R5 BY -1;
    R1 = 8;
    R0 = R0 + R1;
    R0 = LSHIFT R0 BY 2;
    R1 = I1;
    R0 = R0 + R1;
    I2 = R0;
    R0 = DM(0, I2);
    R1 = FEXT R5 BY 0:1;
    R1 = LSHIFT R1 BY 4;
    R1 = -R1;
    R0 = LSHIFT R0 BY R1;
    R0 = FEXT R0 BY 0:16;
    R1 = DM(_iv_lock_source_flag);
    R1 = PASS R1;
    IF NE JUMP _iv_lock_source_save;
    R0 = PASS R0;
    IF NE JUMP _iv_lock_bad;
_iv_lock_source_save:
    // Captured source values are still untrusted at this boundary. Validate
    // their exact family ranges before allowing a note to be acknowledged.
    R1 = DM(_iv_lock_source_flag);
    R1 = PASS R1;
    IF EQ JUMP _iv_lock_source_store;
    R5 = PASS R5;
    IF NE JUMP _iv_lock_source_high;
    R1 = 127;
    COMP(R0, R1);
    IF GT JUMP _iv_lock_bad;
    JUMP _iv_lock_source_store;
_iv_lock_source_high:
    R1 = R5 - 1;
    R2 = 12;
    COMP(R1, R2);
    IF GE JUMP _iv_lock_source_wtfm;
    R2 = DM(_iv_lock_wave_value);
    R3 = 7;
    COMP(R2, R3);
    IF EQ JUMP _iv_lock_source_fm;
    R2 = 3;
    COMP(R1, R2);
    IF NE JUMP _iv_lock_source_wt_max;
    R2 = 1;
    COMP(R0, R2);
    IF LT JUMP _iv_lock_bad;
_iv_lock_source_wt_max:
    R2 = _iv_wt_high_max;
    JUMP _iv_lock_source_max;
_iv_lock_source_fm:
    R2 = _iv_fm_high_max;
    JUMP _iv_lock_source_max;
_iv_lock_source_wtfm:
    R1 = R1 - R2;
    R2 = _iv_wtfm_high_max;
_iv_lock_source_max:
    R1 = LSHIFT R1 BY 2;
    R1 = R1 + R2;
    I2 = R1;
    R1 = DM(0, I2);
    COMP(R0, R1);
    IF GT JUMP _iv_lock_bad;
_iv_lock_source_store:
    R1 = LSHIFT R5 BY 2;
    R2 = _iv_lock_staging;
    R3 = 28;
    R2 = R2 + R3;
    R1 = R1 + R2;
    I2 = R1;
    DM(0, I2) = R0;
    R5 = R5 + 1;
    R0 = 17;
    COMP(R5, R0);
    IF LT JUMP _iv_lock_source_copy;
    R0 = 1;
    DM(_iv_lock_staged) = R0;
_iv_lock_ok:
    R0 = 1;
    RTS;
_iv_lock_bad:
    R0 = 0;
    RTS;

// Slot-local snapshot; R0 is ignored by callers. 24 words per slot.
_iv_lock_commit:
    R0 = DM(_iv_lock_staged);
    R0 = PASS R0;
    IF EQ RTS;
    R0 = DM(_iv_slot);
    R1 = 96;
    R0 = R0 * R1 (SSI);
    R1 = _iv_lock_slots;
    R0 = R0 + R1;
    I0 = R0;
    I1 = _iv_lock_staging;
    R1 = 24;
_iv_lock_commit_word:
    R0 = DM(I1, M6);
    DM(I0, M6) = R0;
    R1 = R1 - 1;
    IF NE JUMP _iv_lock_commit_word;
    R0 = 0;
    DM(_iv_lock_staged) = R0;
    RTS;
_iv_lock_clear:
    R0 = DM(_iv_slot);
    R1 = 96;
    R0 = R0 * R1 (SSI);
    R1 = _iv_lock_slots;
    R0 = R0 + R1;
    I0 = R0;
    R0 = 0;
    DM(0, I0) = R0;
    RTS;
// Apply the slot's absolute values to private scratch before native MOD.
// R4=accepted bank, R0=base or scratch. Clobbers R0..15/I0..2.
.GLOBAL _iv_lock_overlay;
_iv_lock_overlay:
    R0 = DM(_iv_slot);
    R1 = 96;
    R0 = R0 * R1 (SSI);
    R1 = _iv_lock_slots;
    R0 = R0 + R1;
    I0 = R0;
    R0 = DM(0, I0);
    R0 = PASS R0;
    IF EQ JUMP _iv_lock_overlay_none;
    DM(_iv_lock_work_count) = R0;
    R0 = I0;
    R1 = 4;
    R0 = R0 + R1;
    DM(_iv_lock_work_pairs) = R0;
    I0 = R4;
    I1 = _iv_lock_controls;
    R2 = 32;
_iv_lock_overlay_copy:
    R0 = DM(I0, M6);
    DM(I1, M6) = R0;
    R2 = R2 - 1;
    IF NE JUMP _iv_lock_overlay_copy;
    // A wave lock carries the remembered source bank in this same snapshot.
    // Install it into scratch first, then apply other locks for that family.
    R0 = DM(_iv_lock_work_pairs);
    R1 = 20;
    R0 = R0 + R1;
    I0 = R0;
    R0 = DM(0, I0);
    R0 = PASS R0;
    IF EQ JUMP _iv_lock_overlay_start;
    R0 = DM(_iv_lock_work_pairs);
    I1 = R0;
    R10 = DM(_iv_lock_work_count);
_iv_lock_find_wave:
    R0 = DM(I1, M6);
    R1 = LSHIFT R0 BY -10;
    R2 = 34;
    COMP(R1, R2);
    IF EQ JUMP _iv_lock_wave_found;
    R10 = R10 - 1;
    IF NE JUMP _iv_lock_find_wave;
    JUMP _iv_lock_overlay_start;
_iv_lock_wave_found:
    R8 = FEXT R0 BY 0:10;
    R0 = DM(_iv_lock_work_pairs);
    R1 = 24;
    R0 = R0 + R1;
    I2 = R0;
    R0 = DM(I2, M6); // remembered COLOR / FM depth
    I0 = _iv_lock_controls;
    DM(2, I0) = R0;
    R1 = DM(18, I0);
    R1 = LSHIFT R1 BY -16;
    R1 = LSHIFT R1 BY 16;
    R1 = R1 OR R0;
    DM(18, I0) = R1;
    R0 = 2;
    COMP(R8, R0);
    IF LT JUMP _iv_lock_wave_legacy;
    R0 = 7;
    COMP(R8, R0);
    IF EQ JUMP _iv_lock_wave_fm;
    R0 = 2;
    JUMP _iv_lock_wave_family;
_iv_lock_wave_fm:
    R0 = 3;
    JUMP _iv_lock_wave_family;
_iv_lock_wave_legacy:
    R0 = R8;
_iv_lock_wave_family:
    DM(1, I0) = R0;
    R0 = I0;
    R1 = 64;
    R0 = R0 + R1;
    I0 = R0;
    R10 = 16;
_iv_lock_wave_copy:
    R0 = DM(I0, M5);
    R0 = FEXT R0 BY 0:16;
    R1 = DM(I2, M6);
    R1 = LSHIFT R1 BY 16;
    R0 = R0 OR R1;
    DM(I0, M6) = R0;
    R10 = R10 - 1;
    IF NE JUMP _iv_lock_wave_copy;
_iv_lock_overlay_start:
    R0 = 0;
    DM(_iv_lock_work_index) = R0;
_iv_lock_overlay_next:
    R0 = DM(_iv_lock_work_index);
    R1 = DM(_iv_lock_work_count);
    COMP(R0, R1);
    IF GE JUMP _iv_lock_overlay_constraints;
