"""Generate the seam between the image adapters core/instrument-play and core/midi-events and the service file
services/instrument.dks from `seam.toml` (docs/plans/fork-image-diet.md).

    uv run python -m modules.core.services.instrument.tools.seam          # write the files
    uv run python -m modules.core.services.instrument.tools.seam --check  # exit 1 when a file is stale

Writes, for each vector, the image forwarders (`image_file`); for the service the vector tables, the thunks of the image
functions and the copy of the image table (`dks/src/seam.s`) and the layout its setup checks (`src/seam_gen.rs` of the host crate); the
image table (`instrument-play/src/cf/seam-table.s`) and the C names of the table (`instrument-play/src/cf/seam.h`).
"""

from __future__ import annotations

import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[5]
HERE = Path(__file__).resolve().parents[1]
SPEC = HERE / "seam.toml"
SVC_S = HERE / "dks/src/seam.s"
SVC_RS = HERE / "src/seam_gen.rs"
IMG_TABLE = ROOT / "modules/core/adapters/instrument-play/src/cf/seam-table.s"
IMG_H = ROOT / "modules/core/adapters/instrument-play/src/cf/seam.h"
HEAD = "Generated by modules.core.services.instrument.tools.seam from seam.toml; do not edit."

# The image table: magic, version, word count, then the functions, the optional functions, the data addresses and the registry codes.
FIXED = 3
KINDS = ("functions", "optional", "data", "values")


def load() -> dict:
    return tomllib.loads(SPEC.read_text())


def table_names(spec: dict) -> list[tuple[str, str]]:
    img = spec["image"]
    out: list[tuple[str, str]] = []
    for kind in KINDS:
        out += [(n, kind) for n in img[kind]]
    names = [n for n, _ in out]
    dup = sorted({n for n in names if names.count(n) > 1})
    if dup:
        raise SystemExit(f"seam.toml: {dup} listed twice in [image]")
    return out


def absent_code(absent: str) -> list[str]:
    if absent == "rts":
        return ["rts"]
    if absent == "zero":
        return ["moveq #0,%d0", "rts"]
    if absent == "minus1":
        return ["moveq #-1,%d0", "rts"]
    if absent.startswith("jmp:"):
        return [f"jmp {absent[4:]}"]
    raise SystemExit(f"seam.toml: unknown absent action {absent!r}")


def forwarders(vec: dict) -> str:
    """The image file of one vector: a forwarder per entry. The slot word is `slot.<name>` (the [[slot]] of the adapter)."""
    slot, adapter = vec["slot"], vec["adapter"]
    lines = [
        f"/* {HEAD}",
        f" * Forwarders of {adapter} into services/instrument.dks: each reads the slot word {slot} (0 until the service",
        " * filled it with its table) and jumps through its entry, or takes the path the image had without the code (the stock",
        " * handler, or a neutral result). Clobbers d0 and a0 only, as a C call may; the arguments stay on the stack. */",
        "    .text",
        "    .even",
    ]
    for i, (name, absent) in enumerate(vec["entries"]):
        lines += [
            f"    .globl {name}",
            f"{name}:",
            f"    move.l slot.{slot},%d0",
            "    beq.s 1f",
            "    movea.l %d0,%a0",
            f"    movea.l {4 * i}(%a0),%a0",
            "    jmp (%a0)",
            "1:",
        ]
        lines += ["    " + c for c in absent_code(absent)]
    return "\n".join(lines) + "\n"


def image_table(spec: dict) -> str:
    img = spec["image"]
    names = table_names(spec)
    lines = [
        f"/* {HEAD}",
        f" * The image table {img['info']} of core/instrument-play (its [[info]]): magic, version, word count, then the addresses",
        " * services/instrument.dks takes from the image (an optional function the image lacks is 0) and the registry codes. */",
        "    .section .rodata",
        "    .balign 4",
        f"    .globl {img['symbol']}",
        f"{img['symbol']}:",
        f"    .long {img['magic']:#010x}",
        f"    .long {spec['version']}",
        f"    .long {FIXED + len(names)}",
    ]
    lines += [f"    .long {n}" for n, _ in names]
    return "\n".join(lines) + "\n"


def service_asm(spec: dict) -> str:
    names = table_names(spec)
    words = FIXED + len(names)
    lines = [
        f"/* {HEAD}",
        " * The vector tables the service fills the image's slot words with, the thunks through which the moved C code calls the",
        " * image (each clobbers a0, as a C call may), and ip_img, the copy of the image table that setup makes (seam.rs). */",
        "    .section .rodata",
        "    .balign 4",
    ]
    for vec in spec["vector"]:
        lines += [f"    .globl {vec['table']}", f"{vec['table']}:"]
        lines += [f"    .long {n}" for n, _ in vec["entries"]]
    lines += ["    .text", "    .even"]
    for i, (n, kind) in enumerate(names):
        if kind in ("functions", "optional"):
            lines += [f"    .globl {n}", f"{n}:", f"    movea.l ip_img+{4 * (FIXED + i)},%a0", "    jmp (%a0)"]
    lines += ["    .bss", "    .balign 4", "    .globl ip_img", f"ip_img: .space {4 * words}"]
    return "\n".join(lines) + "\n"


def service_rs(spec: dict) -> str:
    names = table_names(spec)
    img = spec["image"]
    req = [FIXED + i for i, (_, k) in enumerate(names) if k in ("functions", "data")]
    return "\n".join(
        [
            f"// {HEAD}",
            "/// The name of the image table (`[[info]]` of core/instrument-play).",
            f"pub const INFO: &str = \"{img['info']}\";",
            f"pub const MAGIC: u32 = {img['magic']:#010x};",
            f"pub const VERSION: u32 = {spec['version']};",
            "/// Words of the table: magic, version, count, then one per name.",
            f"pub const WORDS: usize = {FIXED + len(names)};",
            "/// The words that must not be 0 (functions and data of the adapter itself).",
            f"pub const REQUIRED: [usize; {len(req)}] = {req};",
            "",
        ]
    )


def header(spec: dict) -> str:
    names = table_names(spec)
    img = spec["image"]
    lines = [
        f"/* {HEAD}",
        f" * The image table {img['info']} as the C code names it. In the service build (DK_SERVICE) the moved code reads the",
        " * service's copy ip_img: IP_HAVE(f) tests an optional function, IP_DATA(name) is a data address, IP_VALUE(name) a",
        " * registry code. In the image build they are the plain symbols. */",
        "#ifndef DK_INSTRUMENT_SEAM_H",
        "#define DK_INSTRUMENT_SEAM_H",
        "#include <stdint.h>",
        f"#define IP_SEAM_MAGIC {img['magic']:#010x}u",
        f"#define IP_SEAM_VERSION {spec['version']}u",
        f"#define IP_SEAM_WORDS {FIXED + len(names)}u",
    ]
    lines += [f"#define IPX_{n} {FIXED + i}u" for i, (n, _) in enumerate(names)]
    lines += [
        "#ifdef DK_SERVICE",
        "extern volatile uint32_t ip_img[IP_SEAM_WORDS];",
        "#define IP_HAVE(f) (ip_img[IPX_##f] != 0)",
        "#define IP_DATA(n) ((uintptr_t)ip_img[IPX_##n])",
        "#define IP_VALUE(n) (ip_img[IPX_##n])",
        "#else",
        "#define IP_HAVE(f) ((f) != 0)",
        "#define IP_DATA(n) ((uintptr_t)&(n))",
        "#define IP_VALUE(n) ((uint32_t)(uintptr_t)&(n))",
        "#endif",
        "#endif",
    ]
    return "\n".join(lines) + "\n"


def outputs(spec: dict) -> dict[Path, str]:
    out = {ROOT / v["image_file"]: forwarders(v) for v in spec["vector"]}
    out[IMG_TABLE] = image_table(spec)
    out[IMG_H] = header(spec)
    out[SVC_S] = service_asm(spec)
    out[SVC_RS] = service_rs(spec)
    return out


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    for path, text in outputs(load()).items():
        if path.exists() and path.read_bytes() == text.encode():
            continue
        if check:
            stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(text.encode())
            print(f"wrote {path.relative_to(ROOT)}")
    for p in stale:
        print(f"stale: {p} (run uv run python -m modules.core.services.instrument.tools.seam)")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
