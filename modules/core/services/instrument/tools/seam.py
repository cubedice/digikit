"""Generate the seam between image adapters and a service file from a `seam.toml` (docs/plans/fork-image-diet.md): the
instrument service (`modules/core/services/instrument/seam.toml`, services/instrument.dks) and the track keyboard service
(`modules/core/services/track-keyboard/seam.toml`, services/track-keyboard.dks).

    uv run python -m modules.core.services.instrument.tools.seam          # write the files of every seam.toml
    uv run python -m modules.core.services.instrument.tools.seam --check  # exit 1 when a file is stale
    uv run python -m modules.core.services.instrument.tools.seam SPEC     # one seam.toml only

Writes, for each vector, the image forwarders (`image_file`); for the service the vector tables, the thunks of the image
functions and the copy of the image table (`[output] service_asm`) and the layout its setup checks (`service_rs`); the image
table (`image_table`) and the C names of the table (`header`).
"""

from __future__ import annotations

import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[5]
HERE = Path(__file__).resolve().parents[1]
SPECS = sorted(ROOT.glob("modules/core/services/*/seam.toml"))
TOOL = "modules.core.services.instrument.tools.seam"

# The image table: magic, version, word count, then the functions, the optional functions, the data addresses and the registry codes.
FIXED = 3
KINDS = ("functions", "optional", "data", "values")

# `[output]` of a seam.toml: where the files go and the names of the C side. The defaults are the instrument service's.
OUTPUT = {
    "service_file": "services/instrument.dks",
    "adapter": "core/instrument-play",
    "image_table": "modules/core/adapters/instrument-play/src/cf/seam-table.s",
    "header": "modules/core/adapters/instrument-play/src/cf/seam.h",
    "guard": "DK_INSTRUMENT_SEAM_H",
    "prefix": "IP",
    "copy": "ip_img",
    "service_asm": "dks/src/seam.s",
    "service_rs": "src/seam_gen.rs",
}


def load(path: Path) -> dict:
    spec = tomllib.loads(path.read_text())
    spec["output"] = {**OUTPUT, **spec.get("output", {})}
    spec["_dir"] = path.parent
    rel = path.relative_to(ROOT).as_posix()
    # the instrument's files name their spec as the tool's own (`seam.toml`), as before there were two
    spec["_head"] = (
        f"Generated by {TOOL} from {'seam.toml' if path.parent == HERE else rel}; do not edit."
    )
    return spec


def table_names(spec: dict) -> list[tuple[str, str]]:
    img = spec["image"]
    out: list[tuple[str, str]] = []
    for kind in KINDS:
        out += [(n, kind) for n in img.get(kind, [])]
    names = [n for n, _ in out]
    dup = sorted({n for n in names if names.count(n) > 1})
    if dup:
        raise SystemExit(f"seam.toml: {dup} listed twice in [image]")
    return out


def absent_code(absent: str) -> list[str]:
    if absent == "rts":
        return ["rts"]
    if absent == "zero":
        return ["moveq #0,%d0", "rts"]
    if absent == "minus1":
        return ["moveq #-1,%d0", "rts"]
    if absent.startswith("jmp:"):
        return [f"jmp {absent[4:]}"]
    raise SystemExit(f"seam.toml: unknown absent action {absent!r}")


def forwarders(spec: dict, vec: dict) -> str:
    """The image file of one vector: a forwarder per entry. The slot word is `slot.<name>` (the [[slot]] of the adapter)."""
    slot, adapter = vec["slot"], vec["adapter"]
    lines = [
        f"/* {spec['_head']}",
        f" * Forwarders of {adapter} into {spec['output']['service_file']}: each reads the slot word {slot} (0 until the service",
        " * filled it with its table) and jumps through its entry, or takes the path the image had without the code (the stock",
        " * handler, or a neutral result). Clobbers d0 and a1 only, as a C call may; the arguments stay on the stack, and a0, the address",
        " * of a returned struct in this ABI (m68k-elf GCC), reaches the target. */",
        "    .text",
        "    .even",
    ]
    for i, entry in enumerate(vec["entries"]):
        name, absent = entry[0], entry[1]
        lines += [
            f"    .globl {name}",
            f"{name}:",
            f"    move.l slot.{slot},%d0",
            "    beq.s 1f",
            "    movea.l %d0,%a1",
            f"    movea.l {4 * i}(%a1),%a1",
            "    jmp (%a1)",
            "1:",
        ]
        lines += ["    " + c for c in absent_code(absent)]
    return "\n".join(lines) + "\n"


def image_table(spec: dict) -> str:
    img, out = spec["image"], spec["output"]
    names = table_names(spec)
    lines = [
        f"/* {spec['_head']}",
        f" * The image table {img['info']} of {out['adapter']} (its [[info]]): magic, version, word count, then the addresses",
        f" * {out['service_file']} takes from the image (an optional function the image lacks is 0) and the registry codes. */",
        "    .section .rodata",
        "    .balign 4",
        f"    .globl {img['symbol']}",
        f"{img['symbol']}:",
        f"    .long {img['magic']:#010x}",
        f"    .long {spec['version']}",
        f"    .long {FIXED + len(names)}",
    ]
    lines += [f"    .long {n}" for n, _ in names]
    return "\n".join(lines) + "\n"


def service_asm(spec: dict) -> str:
    names = table_names(spec)
    copy = spec["output"]["copy"]
    words = FIXED + len(names)
    lines = [
        f"/* {spec['_head']}",
        " * The vector tables the service fills the image's slot words with, the thunks through which the moved C code calls the",
        f" * image (each clobbers a1, as a C call may, and keeps a0, the address of a returned struct), and {copy}, the copy of the",
        " * image table that setup makes (seam.rs). */",
        "    .section .rodata",
        "    .balign 4",
    ]
    for vec in spec["vector"]:
        lines += [f"    .globl {vec['table']}", f"{vec['table']}:"]
        # an entry may name the service function it forwards to when the image's name differs (`[image name, absent, target]`)
        lines += [f"    .long {e[2] if len(e) > 2 else e[0]}" for e in vec["entries"]]
    lines += ["    .text", "    .even"]
    for i, (n, kind) in enumerate(names):
        if kind in ("functions", "optional"):
            lines += [
                f"    .globl {n}",
                f"{n}:",
                f"    movea.l {copy}+{4 * (FIXED + i)},%a1",
                "    jmp (%a1)",
            ]
    lines += [
        "    .bss",
        "    .balign 4",
        f"    .globl {copy}",
        f"{copy}: .space {4 * words}",
    ]
    return "\n".join(lines) + "\n"


def service_rs(spec: dict) -> str:
    names = table_names(spec)
    img = spec["image"]
    req = [FIXED + i for i, (_, k) in enumerate(names) if k in ("functions", "data")]
    return "\n".join(
        [
            f"// {spec['_head']}",
            f"/// The name of the image table (`[[info]]` of {spec['output']['adapter']}).",
            f'pub const INFO: &str = "{img["info"]}";',
            f"pub const MAGIC: u32 = {img['magic']:#010x};",
            f"pub const VERSION: u32 = {spec['version']};",
            "/// Words of the table: magic, version, count, then one per name.",
            f"pub const WORDS: usize = {FIXED + len(names)};",
            "/// The words that must not be 0 (functions and data of the adapter itself).",
            f"pub const REQUIRED: [usize; {len(req)}] = {req};",
            "",
        ]
    )


def header(spec: dict) -> str:
    names = table_names(spec)
    img, out = spec["image"], spec["output"]
    p, copy = out["prefix"], out["copy"]
    lines = [
        f"/* {spec['_head']}",
        f" * The image table {img['info']} as the C code names it. In the service build (DK_SERVICE) the moved code reads the",
        f" * service's copy {copy}: {p}_HAVE(f) tests an optional function, {p}_DATA(name) is a data address, {p}_VALUE(name) a",
        " * registry code. In the image build they are the plain symbols. */",
        f"#ifndef {out['guard']}",
        f"#define {out['guard']}",
        "#include <stdint.h>",
        f"#define {p}_SEAM_MAGIC {img['magic']:#010x}u",
        f"#define {p}_SEAM_VERSION {spec['version']}u",
        f"#define {p}_SEAM_WORDS {FIXED + len(names)}u",
    ]
    lines += [f"#define {p}X_{n} {FIXED + i}u" for i, (n, _) in enumerate(names)]
    lines += [
        "#ifdef DK_SERVICE",
        f"extern volatile uint32_t {copy}[{p}_SEAM_WORDS];",
        f"#define {p}_HAVE(f) ({copy}[{p}X_##f] != 0)",
        f"#define {p}_DATA(n) ((uintptr_t){copy}[{p}X_##n])",
        f"#define {p}_VALUE(n) ({copy}[{p}X_##n])",
        "#else",
        f"#define {p}_HAVE(f) ((f) != 0)",
        f"#define {p}_DATA(n) ((uintptr_t)&(n))",
        f"#define {p}_VALUE(n) ((uint32_t)(uintptr_t)&(n))",
        "#endif",
        "#endif",
    ]
    return "\n".join(lines) + "\n"


def outputs(spec: dict) -> dict[Path, str]:
    out = spec["output"]
    files = {ROOT / v["image_file"]: forwarders(spec, v) for v in spec["vector"]}
    files[ROOT / out["image_table"]] = image_table(spec)
    files[ROOT / out["header"]] = header(spec)
    files[spec["_dir"] / out["service_asm"]] = service_asm(spec)
    files[spec["_dir"] / out["service_rs"]] = service_rs(spec)
    return files


def main(argv: list[str]) -> int:
    check = "--check" in argv
    specs = [Path(a).resolve() for a in argv if not a.startswith("--")] or SPECS
    stale = []
    for spec in specs:
        for path, text in outputs(load(spec)).items():
            if path.exists() and path.read_bytes() == text.encode():
                continue
            if check:
                stale.append(path.relative_to(ROOT))
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(text.encode())
                print(f"wrote {path.relative_to(ROOT)}")
    for p in stale:
        print(f"stale: {p} (run uv run python -m {TOOL})")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
